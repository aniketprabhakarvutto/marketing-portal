from __future__ import annotations

import unittest
from pathlib import Path

from portal import db
from portal.migrations import MIGRATIONS
from portal.models import TABLE_MODELS, postgres_schema


class PostgresMigrationTests(unittest.TestCase):
    def test_models_cover_every_persisted_table(self) -> None:
        names = {model.table for model in TABLE_MODELS}
        self.assertEqual(names, set(db.ALL_TABLES))

    def test_postgres_schema_is_not_sqlite_specific(self) -> None:
        schema = postgres_schema(db.SCHEMA)
        self.assertIn("GENERATED BY DEFAULT AS IDENTITY", schema)
        self.assertIn("TO_CHAR(CURRENT_TIMESTAMP AT TIME ZONE 'UTC'", schema)
        self.assertNotIn("datetime('now')", schema)
        self.assertNotIn("CREATE TABLE IF NOT EXISTS paid_metrics (\n    id               INTEGER PRIMARY KEY", schema)
        self.assertIn("origin      TEXT    NOT NULL DEFAULT 'rollup'", db.SCHEMA)

    def test_crm_provenance_forward_migration_is_registered(self) -> None:
        self.assertIn("0002_crm_origins", MIGRATIONS)

    def test_migration_history_is_qualified_to_public_schema(self) -> None:
        migration_source = (Path(__file__).resolve().parents[1] / "portal" / "migrations" / "__init__.py").read_text()
        self.assertIn("public.schema_migrations", migration_source)

    def test_postgres_runtime_keeps_sqlite_datetime_text_shape(self) -> None:
        translated = db._postgres_sql("SELECT datetime('now')")
        self.assertIn("TO_CHAR(CURRENT_TIMESTAMP AT TIME ZONE 'UTC'", translated)
        self.assertNotIn("datetime('now')", translated)

    def test_postgres_runtime_translates_sqlite_datetime_modifiers(self) -> None:
        translated = db._postgres_sql("SELECT datetime('now', ?), datetime('now','-30 days')")
        self.assertIn("%s)::interval", translated)
        self.assertIn("INTERVAL '-30 days'", translated)


if __name__ == "__main__":
    unittest.main()
