def postgres_schema(sqlite_schema: str) -> str:
    """Translate the shared initial schema into PostgreSQL DDL.

    The initial schema uses a conservative SQL subset.  This narrow conversion
    keeps SQLite for local development while producing equivalent PostgreSQL
    tables, indexes, constraints, defaults, and identity primary keys.
    """
    schema = sqlite_schema
    schema = re.sub(
        r"\bid\s+INTEGER\s+PRIMARY\s+KEY\b",
        "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
        schema,
        flags=re.IGNORECASE,
    )
    schema = re.sub(r"\bREAL\b", "DOUBLE PRECISION", schema, flags=re.IGNORECASE)
    schema = re.sub(
        r"\(datetime\('now'\)\)",
        "TO_CHAR(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')",
        schema,
        flags=re.IGNORECASE,
    )
    return schema

